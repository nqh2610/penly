    let uiLang = 'en';

    function t(key, vars) {
      let s = (LANG[uiLang] || LANG.en)[key] || key;
      if (vars) Object.entries(vars).forEach(([k, v]) => s = s.replace('{' + k + '}', v));
      return s;
    }

    function setLang(lang) {
      uiLang = lang;
      localStorage.setItem('ui_lang', lang);
      document.getElementById('langVI').classList.toggle('on', lang === 'vi');
      document.getElementById('langEN').classList.toggle('on', lang === 'en');

      // update all labelled elements
      const ids = [
        'lbl-brand-sub', 'lbl-new-doc', 'lbl-my-docs', 'lbl-export', 'lbl-import', 'lbl-delete',
        'lbl-aud', 'lbl-tone', 'lbl-lvl', 'lbl-topic',
        'lbl-btn-outline', 'lbl-btn-vocab', 'lbl-btn-grammar', 'lbl-btn-suggest',
        'lbl-btn-improve', 'lbl-btn-review', 'lbl-btn-translate',
        'lbl-sd-lang', 'lbl-sd-theme', 'lbl-theme-light', 'lbl-theme-dark', 'lbl-sd-accent',
        'lbl-sd-uifs', 'lbl-sd-edfs', 'lbl-sd-lh', 'lbl-sd-font', 'lbl-sd-pw', 'lbl-sd-pad',
        'lbl-pad-c', 'lbl-pad-n', 'lbl-pad-w',
        'aud-children', 'aud-friends', 'aud-public', 'aud-pro',
        'tone-story', 'tone-casual', 'tone-humor', 'tone-pro', 'tone-persuade', 'tone-emo',
        'font-bevietnam', 'font-georgia', 'font-system', 'font-courier',
      ];
      ids.forEach(id => {
        const el = document.getElementById(id);
        if (el) el.textContent = t(id);
      });

      // settings drawer title
      const sdTitle = document.querySelector('.sd-head-title');
      if (sdTitle) sdTitle.textContent = t('lbl-sd-title');

      // placeholders
      document.getElementById('topicInput').placeholder = t('topicInput-ph');
      document.getElementById('editor').setAttribute('data-placeholder', t('editor-ph'));
      const dsi = document.getElementById('docSearchInput');
      if (dsi) dsi.placeholder = t('doc-search-ph');
      updateDocSortUI();

      // topbar doc title display
      updateDocTitleDisplay();

      // saveStatus if showing initial text
      const ss = document.getElementById('saveStatus');
      if (ss && (ss.textContent === LANG.vi['saveStatus-init'] || ss.textContent === LANG.en['saveStatus-init']))
        ss.textContent = t('saveStatus-init');

      // wc counter unit
      updateWC();
    }
